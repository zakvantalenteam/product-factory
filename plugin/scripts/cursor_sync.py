"""Generate the Cursor copies of a repo's Claude setup (agent core + project layer).

.claude/ is the single source. This writes, in the repo:
  .cursor/rules/<name>.mdc   from .claude/rules/<name>.md   (paths: -> globs:)
  .cursor/agents/<name>.md   from .claude/agents/<name>.md  (model: inherit, readonly when the agent cannot write)
  .cursor/hooks.json         runs the core guard (blocks), rules_check (after edits), live_status hook (live page)
                             and flow_check stop (flow check) from .cursor/runtime/
  .cursor/runtime/           the runtime those hooks run: guard, rules and flow checks, project.py, live_status (and
                             its page) with the scripts they import, copied from the core this script runs from and
                             stamped with its version, so Cursor keeps the guard when .claude/core/ goes
In a repo that does not carry the core (no .claude/core/core.lock: Claude gets it from the plugin) it also writes
the whole core for Cursor, which cannot load Claude plugins: .cursor/agents/ and .cursor/skills/ for the core agents
and skills the repo has no own copy of, and every core script, reference and template in .cursor/runtime/, with the
core paths in their text pointing there. AGENTS.md and .claude/skills/ need no copy: Cursor reads them directly.

Usage: python <core>/scripts/cursor_sync.py [--check | --fix-settings]   (<core>: .claude/core or the plugin folder)
  --check         write nothing; exit 1 and list the files that are stale or missing.
  --fix-settings  rewrite hook commands in .claude/settings.json that start a script as
                  `python "$CLAUDE_PROJECT_DIR/..."` to the Claude launcher (Cursor runs those hooks too, without
                  CLAUDE_PROJECT_DIR, and python's exit 2 there blocked every tool call). Both other modes list them.
Both modes also list agent and skill headers Claude Code cannot read (invalid YAML: the agent silently disappears,
a skill loses its description); --check exits 1 on them. Line endings follow `newline` in .claude/project.json.
"""
import json
import os
import re
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import project  # noqa: E402

ROOT = project.repo_root()
NEWLINE = "\r\n" if str(project.config(ROOT).get("newline", "lf")).lower() == "crlf" else "\n"
MARK = "Generated by the agent core's cursor_sync.py from {src}. Edit the source, then run the script."
# Cursor can start a hook outside the project (on Windows even in another drive's root) and may run it in cmd,
# PowerShell or bash, so neither a relative path nor a $VAR/%VAR% path works everywhere. Python finds the project
# from CURSOR_PROJECT_DIR, else the first of the hook input's workspace_roots (also as "/d:/..."), runs the script
# from there, and skips a missing script or any launcher error instead of blocking.
RUN = ("python -c \"import io,json,os,sys,runpy;sys.excepthook=lambda *a:os._exit(0);d=sys.stdin.buffer.read();"
       "r=os.environ.get('CURSOR_PROJECT_DIR') or os.environ.get('CLAUDE_PROJECT_DIR') or "
       "(json.loads(d or b'{}').get('workspace_roots') or ['.'])[0];r=r[1:] if r[:1]=='/' and r[2:3]==':' else r;"
       "p=os.path.join(r,sys.argv[1]);os.path.isfile(p) or sys.exit(0);os.chdir(r);sys.argv=[p]+sys.argv[2:];"
       "sys.path.insert(0,os.path.dirname(p));sys.stdin=io.TextIOWrapper(io.BytesIO(d),encoding='utf-8');"
       "sys.excepthook=sys.__excepthook__;runpy.run_path(p,run_name='__main__')\" ")
# a missing runtime script or a launcher error leaves one warning line on stderr (Cursor's hook output)
RUN = RUN.replace("sys.excepthook=lambda *a:os._exit(0);",
                  "sys.excepthook=lambda t,v,b:(sys.stderr.write('agent core hook launcher failed: '+repr(v)+'\\n'),"
                  "sys.stderr.flush(),os._exit(0));", 1).replace(
    "os.path.isfile(p) or sys.exit(0);",
    "os.path.isfile(p) or (sys.stderr.write('agent core: '+p+' is missing; run cursor_sync.py\\n'),sys.exit(0));")
RT = ".cursor/runtime/"
GUARD = RUN + RT + "hooks/guard.py --cursor"
RULES_CHECK = RUN + RT + "hooks/rules_check.py --cursor"
LIVE = RUN + RT + "scripts/live_status.py hook --cursor"
FLOW_STOP = RUN + RT + "hooks/flow_check.py stop --cursor"
CORE = project.CORE_DIR
# what Cursor's hooks run, and what those scripts import (live_status: timing, handoff_check; flow_check: scope_check)
RUNTIME = ["VERSION", "hooks/guard.py", "hooks/rules_check.py", "hooks/flow_check.py", "scripts/project.py",
           "scripts/live_status.py", "scripts/live_status.html", "scripts/timing.py", "scripts/scope_check.py",
           "scripts/handoff_check.py"]
FULL_SKIP = {"__pycache__", "hooks.json", "session_start.py", "build_plugin.py", "core-plan.md", "core.lock",
             "exam-scores.json", "migration", ".claude-plugin"}
MANIFEST = RT + "manifest.json"  # the generated .cursor/skills/ files, so a dropped one is removed
EDIT_TOOLS = "Write|Edit|StrReplace|MultiEdit"
SETTINGS = ".claude/settings.json"
DIRECT = re.compile(r'^python "\$CLAUDE_PROJECT_DIR/([^"]+)"(.*)$')


def claude_run():
    """The Claude hook launcher (runs a script only for Claude Code), from the core's settings template."""
    tpl = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "templates", "settings-hooks.json")
    with open(tpl, encoding="utf-8") as f:
        for arr in json.load(f)["hooks"].values():
            for m in arr:
                for h in m.get("hooks", []):
                    hit = re.match(r'(python -c "[^"]*" )', h.get("command", ""))
                    if hit:
                        return hit.group(1)
    raise ValueError("no launcher in " + tpl)


def settings_hooks(fix=False):
    """Hook commands in .claude/settings.json that start a script through "$CLAUDE_PROJECT_DIR/..."; with fix=True
    they are rewritten to the launcher in place, keeping the file's layout and line endings."""
    full = os.path.join(ROOT, SETTINGS)
    if not os.path.isfile(full):
        return []
    with open(full, encoding="utf-8", newline="") as f:
        raw = f.read()
    text = raw.replace("\r\n", "\n")
    found = []
    for arr in (json.loads(text).get("hooks") or {}).values():
        for m in arr:
            for h in m.get("hooks", []):
                mt = DIRECT.match(h.get("command", ""))
                if mt:
                    found.append(h["command"])
                    if fix:
                        text = text.replace(json.dumps(h["command"]),
                                            json.dumps(claude_run() + mt.group(1) + mt.group(2)))
    if fix and found:
        json.loads(text)
        with open(full, "w", encoding="utf-8", newline="") as f:
            f.write(text.replace("\n", "\r\n") if "\r\n" in raw else text)
    return found


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def split_front(text):
    m = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    return (m.group(1), m.group(2)) if m else ("", text)


def field(front, name):
    m = re.search(r"^" + name + r":[ \t]*(.*)$", front, re.M)
    return m.group(1).strip() if m else ""


def rule(src):
    front, body = split_front(read(src))
    globs = re.findall(r"^\s*-\s*[\"']?([^\"'\n]+)[\"']?\s*$", front, re.M)
    title = re.search(r"^#\s+(.+)$", body, re.M)
    desc = (title.group(1) if title else os.path.basename(src)[:-3]) + " rules for this repo"
    head = "---\ndescription: %s\nglobs: %s\nalwaysApply: false\n---\n" % (desc, ",".join(globs))
    return head + "<!-- " + MARK.format(src=src) + " -->\n" + body.lstrip("\n")


def agent(src, text=None):
    front, body = split_front(read(src) if text is None else text)
    tools = field(front, "tools")
    readonly = bool(tools) and not re.search(r"\b(Write|Edit)\b", tools)
    head = "---\nname: %s\ndescription: %s\nmodel: inherit\n" % (field(front, "name"), field(front, "description"))
    if readonly:
        head += "readonly: true\n"
    return head + "---\n<!-- " + MARK.format(src=src) + " -->\n" + body.lstrip("\n")


def switched():
    """True when the repo does not carry the core (no .claude/core/core.lock): Claude gets it from the plugin."""
    return not os.path.isfile(os.path.join(ROOT, ".claude", "core", "core.lock"))


def core_version():
    try:
        with open(os.path.join(CORE, "VERSION"), encoding="utf-8") as f:
            return f.read().strip()
    except OSError:
        return "?"


def core_text(rel):
    """A core file's text for the Cursor copy; in markdown the core paths point at .cursor/runtime/."""
    with open(os.path.join(CORE, rel), encoding="utf-8") as f:
        text = f.read().replace("\r\n", "\n")
    if rel.endswith(".md"):
        text = text.replace("${CLAUDE_PLUGIN_ROOT}/", RT).replace(".claude/core/", RT)
    return text


def core_walk(tops):
    out = []
    for top in tops:
        for d, dirs, files in os.walk(os.path.join(CORE, top)):
            dirs[:] = sorted(x for x in dirs if x not in FULL_SKIP)
            for name in sorted(files):
                if name not in FULL_SKIP and not name.endswith(".pyc"):
                    out.append(os.path.relpath(os.path.join(d, name), CORE).replace("\\", "/"))
    return out


def runtime():
    """{.cursor/... path: text}: the runtime Cursor's hooks run; in a switched repo also the whole core (core agents
    and skills the repo has no own copy of, every script, reference and template)."""
    out = {}
    full = switched()
    # the whole core, skills included, so cursor_sync.py and install.py --check also run from this copy
    files = ["VERSION"] + core_walk(("agents", "skills", "hooks", "scripts", "reference", "templates")) if full else RUNTIME
    for rel in files:
        out[RT + rel] = core_text(rel)
    out[RT + "README.md"] = (
        "# Agent core runtime for Cursor\n\n<!-- " + MARK.format(src="the agent core " + core_version()) + " -->\n\n"
        "Cursor cannot load the Claude Code plugin, so its hooks (`.cursor/hooks.json`) run these copies: the guard, "
        "the rules and flow checks and the live page. " + ("This repo gets the core from the plugin, so this folder "
        "holds the whole core (scripts, reference, templates) and `.cursor/agents/` and `.cursor/skills/` hold the core "
        "agents and skills. " if full else "") + "Never edit these files: change the core source and run cursor_sync.py.\n")
    if full:
        own_agents = set(os.listdir(os.path.join(ROOT, ".claude", "agents"))) if os.path.isdir(
            os.path.join(ROOT, ".claude", "agents")) else set()
        for rel in core_walk(("agents",)):
            name = rel.split("/")[-1]
            if name.endswith(".md") and name not in own_agents:
                out[".cursor/agents/" + name] = agent("the agent core " + rel, core_text(rel))
        own_skills = set(os.listdir(os.path.join(ROOT, ".claude", "skills"))) if os.path.isdir(
            os.path.join(ROOT, ".claude", "skills")) else set()
        skills = [r for r in core_walk(("skills",)) if r.split("/")[1] not in own_skills]
        for rel in skills:
            out[".cursor/" + rel] = core_text(rel)
        out[MANIFEST] = json.dumps(sorted(".cursor/" + r for r in skills), indent=1) + "\n"
    return out


def hooks():
    def h(command=GUARD, **extra):
        return dict({"command": command, "timeout": 10}, **extra)
    return json.dumps({"version": 1, "hooks": {
        "beforeShellExecution": [h()],
        "beforeReadFile": [h()],
        "preToolUse": [h(matcher="Delete|" + EDIT_TOOLS), h(LIVE, timeout=5, matcher="Task")],
        "postToolUse": [h(RULES_CHECK, matcher=EDIT_TOOLS), h(LIVE, timeout=5)],
        "subagentStart": [h(LIVE, timeout=5)],
        "subagentStop": [h(LIVE, timeout=5)],
        "stop": [h(FLOW_STOP, timeout=5)],
    }}, indent=2) + "\n"


def wanted():
    out = {}
    for d, ext, fn in ((".claude/rules", ".mdc", rule), (".claude/agents", ".md", agent)):
        kind = d.split("/")[1]
        folder = os.path.join(ROOT, d)
        for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            if name.endswith(".md"):
                out[".cursor/%s/%s%s" % (kind, name[:-3], ext)] = fn(d + "/" + name)
    out[".cursor/hooks.json"] = hooks()
    out.update(runtime())
    return out


def generated_on_disk():
    found = []
    for kind in ("rules", "agents"):
        d = os.path.join(ROOT, ".cursor", kind)
        if os.path.isdir(d):
            for name in os.listdir(d):
                p = ".cursor/%s/%s" % (kind, name)
                if os.path.isfile(os.path.join(ROOT, p)) and "cursor_sync.py" in read(p):
                    found.append(p)
    rt = os.path.join(ROOT, *RT.strip("/").split("/"))
    for d, dirs, files in os.walk(rt):
        dirs[:] = [x for x in dirs if x != "__pycache__"]
        found += [os.path.relpath(os.path.join(d, f), ROOT).replace("\\", "/") for f in files if not f.endswith(".pyc")]
    try:
        found += [p for p in json.loads(read(MANIFEST)) if os.path.isfile(os.path.join(ROOT, p))]
    except (OSError, ValueError):
        pass
    return sorted(set(found))


def bad_headers():
    """Agent and skill headers Claude Code cannot parse (project.front_errors)."""
    out = []
    for d in (".claude/agents", ".claude/skills"):
        folder = os.path.join(ROOT, *d.split("/"))
        for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            rel = d + "/" + name + ("/SKILL.md" if d.endswith("skills") else "")
            if not rel.endswith(".md") or not os.path.isfile(os.path.join(ROOT, rel)):
                continue
            out += ["%s: %s; quote or reword it" % (rel, e) for e in project.front_errors(read(rel))]
    return out


def main():
    check = "--check" in sys.argv
    if "--fix-settings" in sys.argv:
        print("%s: %d hook command(s) now use the Claude launcher" % (SETTINGS, len(settings_hooks(fix=True))))
        sys.exit(0)
    bad = bad_headers()
    for b in bad:
        print("header " + b)
    direct = settings_hooks()
    for c in direct:
        print("hook   %s: %s fails in Cursor (it runs these hooks too, without CLAUDE_PROJECT_DIR)" % (SETTINGS, c[:90]))
    me = "python " + project.core_path("scripts/cursor_sync.py")
    if direct:
        print("fix it: " + me + " --fix-settings")
    bad = bad + direct
    want = wanted()
    stale = [p for p, text in want.items() if not os.path.isfile(os.path.join(ROOT, p)) or read(p) != text]
    orphans = [p for p in generated_on_disk() if p not in want]
    if check:
        for p in stale + orphans:
            print(("orphan " if p in orphans else "stale  ") + p)
        print("fix the lines above, then run: " + me if bad else "ok" if not (stale or orphans) else "run: " + me)
        sys.exit(1 if stale or orphans or bad else 0)
    for p in stale:
        full = os.path.join(ROOT, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline=NEWLINE) as f:
            f.write(want[p])
        print("wrote  " + p)
    for p in orphans:
        os.remove(os.path.join(ROOT, p))
        print("removed " + p)
        d = os.path.dirname(os.path.join(ROOT, p))
        while os.path.isdir(d) and not os.listdir(d) and os.path.normcase(d) != os.path.normcase(
                os.path.join(ROOT, ".cursor")):
            os.rmdir(d)
            d = os.path.dirname(d)
    print("%d up to date, %d written, %d removed" % (len(want) - len(stale), len(stale), len(orphans)))


if __name__ == "__main__":
    main()
