"""Generate the Cursor copies of the factory's Claude setup.

.claude/ is the single source. This writes:
  .cursor/agents/<name>.md   from .claude/agents/<name>.md  (model: inherit, readonly when the agent cannot write)
  .cursor/hooks.json         intake_guard (prompt), flow_guard (blocks edits), factory_tracker (agent start/stop)
AGENTS.md and .claude/skills/ need no copy: Cursor reads them directly.
Cursor's beforeSubmitPrompt cannot add context, so the PRD hold-on rule reaches Cursor through AGENTS.md.

Usage: python scripts/cursor_sync.py [--check]
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MARK = "Generated by scripts/cursor_sync.py from {src}. Edit the source, then run the script."
EDIT_TOOLS = "Write|Edit|StrReplace|MultiEdit"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def split_front(text):
    m = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    return (m.group(1), m.group(2)) if m else ("", text)


def field(front, name):
    m = re.search(r"^" + name + r":[ \t]*(.*)$", front, re.M)
    return m.group(1).strip() if m else ""


def agent(src):
    front, body = split_front(read(src))
    tools = field(front, "tools")
    readonly = bool(tools) and not re.search(r"\b(Write|Edit)\b", tools)
    head = "---\nname: %s\ndescription: %s\nmodel: inherit\n" % (field(front, "name"), field(front, "description"))
    if readonly:
        head += "readonly: true\n"
    return head + "---\n<!-- " + MARK.format(src=src) + " -->\n" + body.lstrip("\n")


def hooks():
    def h(script, **extra):
        return dict({"command": "python .claude/hooks/%s --cursor" % script, "timeout": 10}, **extra)
    return json.dumps({"version": 1, "hooks": {
        "beforeSubmitPrompt": [h("intake_guard.py")],
        "preToolUse": [h("flow_guard.py", matcher=EDIT_TOOLS), h("factory_tracker.py", matcher="Task")],
        "subagentStart": [h("factory_tracker.py")],
        "subagentStop": [h("factory_tracker.py")],
    }}, indent=2) + "\n"


def wanted():
    out = {}
    for name in sorted(os.listdir(os.path.join(ROOT, ".claude", "agents"))):
        if name.endswith(".md"):
            out[".cursor/agents/" + name] = agent(".claude/agents/" + name)
    out[".cursor/hooks.json"] = hooks()
    return out


def generated_on_disk():
    d = os.path.join(ROOT, ".cursor", "agents")
    if not os.path.isdir(d):
        return []
    return [".cursor/agents/" + n for n in os.listdir(d) if "cursor_sync.py" in read(".cursor/agents/" + n)]


def main():
    check = "--check" in sys.argv
    want = wanted()
    stale = [p for p, text in want.items() if not os.path.isfile(os.path.join(ROOT, p)) or read(p) != text]
    orphans = [p for p in generated_on_disk() if p not in want]
    if check:
        for p in stale + orphans:
            print(("orphan " if p in orphans else "stale  ") + p)
        print("ok" if not (stale or orphans) else "run: python scripts/cursor_sync.py")
        sys.exit(1 if stale or orphans else 0)
    for p in stale:
        full = os.path.join(ROOT, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as f:
            f.write(want[p])
        print("wrote  " + p)
    for p in orphans:
        os.remove(os.path.join(ROOT, p))
        print("removed " + p)
    print("%d up to date, %d written, %d removed" % (len(want) - len(stale), len(stale), len(orphans)))


if __name__ == "__main__":
    main()
