"""Generate the Cursor copies of a repo's Claude setup (agent core + project layer).

.claude/ is the single source. This writes, in the repo:
  .cursor/rules/<name>.mdc   from .claude/rules/<name>.md   (paths: -> globs:)
  .cursor/agents/<name>.md   from .claude/agents/<name>.md  (model: inherit, readonly when the agent cannot write)
  .cursor/hooks.json         runs the core guard (blocks), rules_check (after edits), live_status hook (live page)
                             and flow_check stop (flow check) from .claude/core/
AGENTS.md and .claude/skills/ need no copy: Cursor reads them directly. Cursor cannot load Claude plugins, so these
copies stay in the repo even when Claude gets the core from a plugin.

Usage: python .claude/core/scripts/cursor_sync.py [--check | --fix-settings]
  --check         write nothing; exit 1 and list the files that are stale or missing.
  --fix-settings  rewrite hook commands in .claude/settings.json that start a script as
                  `python "$CLAUDE_PROJECT_DIR/..."` to the Claude launcher (Cursor runs those hooks too, without
                  CLAUDE_PROJECT_DIR, and python's exit 2 there blocked every tool call). Both other modes list them.
Both modes also list agent headers Claude Code cannot read (an unquoted value with ": " or " #" is not valid YAML,
and the agent silently disappears); --check exits 1 on them. Line endings follow `newline` in .claude/project.json.
"""
import json
import os
import re
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import project  # noqa: E402

ROOT = project.repo_root()
NEWLINE = "\r\n" if str(project.config(ROOT).get("newline", "lf")).lower() == "crlf" else "\n"
MARK = "Generated by .claude/core/scripts/cursor_sync.py from {src}. Edit the source, then run the script."
# Cursor can start a hook outside the project (on Windows even in another drive's root) and may run it in cmd,
# PowerShell or bash, so neither a relative path nor a $VAR/%VAR% path works everywhere. Python finds the project
# from CURSOR_PROJECT_DIR, else the first of the hook input's workspace_roots (also as "/d:/..."), runs the script
# from there, and skips a missing script or any launcher error instead of blocking.
RUN = ("python -c \"import io,json,os,sys,runpy;sys.excepthook=lambda *a:os._exit(0);d=sys.stdin.buffer.read();"
       "r=os.environ.get('CURSOR_PROJECT_DIR') or os.environ.get('CLAUDE_PROJECT_DIR') or "
       "(json.loads(d or b'{}').get('workspace_roots') or ['.'])[0];r=r[1:] if r[:1]=='/' and r[2:3]==':' else r;"
       "p=os.path.join(r,sys.argv[1]);os.path.isfile(p) or sys.exit(0);os.chdir(r);sys.argv=[p]+sys.argv[2:];"
       "sys.path.insert(0,os.path.dirname(p));sys.stdin=io.TextIOWrapper(io.BytesIO(d),encoding='utf-8');"
       "sys.excepthook=sys.__excepthook__;runpy.run_path(p,run_name='__main__')\" ")
GUARD = RUN + ".claude/core/hooks/guard.py --cursor"
RULES_CHECK = RUN + ".claude/core/hooks/rules_check.py --cursor"
LIVE = RUN + ".claude/core/scripts/live_status.py hook --cursor"
FLOW_STOP = RUN + ".claude/core/hooks/flow_check.py stop --cursor"
EDIT_TOOLS = "Write|Edit|StrReplace|MultiEdit"
SETTINGS = ".claude/settings.json"
DIRECT = re.compile(r'^python "\$CLAUDE_PROJECT_DIR/([^"]+)"(.*)$')


def claude_run():
    """The Claude hook launcher (runs a script only for Claude Code), from the core's settings template."""
    tpl = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "templates", "settings-hooks.json")
    with open(tpl, encoding="utf-8") as f:
        for arr in json.load(f)["hooks"].values():
            for m in arr:
                for h in m.get("hooks", []):
                    hit = re.match(r'(python -c "[^"]*" )', h.get("command", ""))
                    if hit:
                        return hit.group(1)
    raise ValueError("no launcher in " + tpl)


def settings_hooks(fix=False):
    """Hook commands in .claude/settings.json that start a script through "$CLAUDE_PROJECT_DIR/..."; with fix=True
    they are rewritten to the launcher in place, keeping the file's layout and line endings."""
    full = os.path.join(ROOT, SETTINGS)
    if not os.path.isfile(full):
        return []
    with open(full, encoding="utf-8", newline="") as f:
        raw = f.read()
    text = raw.replace("\r\n", "\n")
    found = []
    for arr in (json.loads(text).get("hooks") or {}).values():
        for m in arr:
            for h in m.get("hooks", []):
                mt = DIRECT.match(h.get("command", ""))
                if mt:
                    found.append(h["command"])
                    if fix:
                        text = text.replace(json.dumps(h["command"]),
                                            json.dumps(claude_run() + mt.group(1) + mt.group(2)))
    if fix and found:
        json.loads(text)
        with open(full, "w", encoding="utf-8", newline="") as f:
            f.write(text.replace("\n", "\r\n") if "\r\n" in raw else text)
    return found


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def split_front(text):
    m = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    return (m.group(1), m.group(2)) if m else ("", text)


def field(front, name):
    m = re.search(r"^" + name + r":[ \t]*(.*)$", front, re.M)
    return m.group(1).strip() if m else ""


def rule(src):
    front, body = split_front(read(src))
    globs = re.findall(r"^\s*-\s*[\"']?([^\"'\n]+)[\"']?\s*$", front, re.M)
    title = re.search(r"^#\s+(.+)$", body, re.M)
    desc = (title.group(1) if title else os.path.basename(src)[:-3]) + " rules for this repo"
    head = "---\ndescription: %s\nglobs: %s\nalwaysApply: false\n---\n" % (desc, ",".join(globs))
    return head + "<!-- " + MARK.format(src=src) + " -->\n" + body.lstrip("\n")


def agent(src):
    front, body = split_front(read(src))
    tools = field(front, "tools")
    readonly = bool(tools) and not re.search(r"\b(Write|Edit)\b", tools)
    head = "---\nname: %s\ndescription: %s\nmodel: inherit\n" % (field(front, "name"), field(front, "description"))
    if readonly:
        head += "readonly: true\n"
    return head + "---\n<!-- " + MARK.format(src=src) + " -->\n" + body.lstrip("\n")


def hooks():
    def h(command=GUARD, **extra):
        return dict({"command": command, "timeout": 10}, **extra)
    return json.dumps({"version": 1, "hooks": {
        "beforeShellExecution": [h()],
        "beforeReadFile": [h()],
        "preToolUse": [h(matcher="Delete|" + EDIT_TOOLS), h(LIVE, timeout=5, matcher="Task")],
        "postToolUse": [h(RULES_CHECK, matcher=EDIT_TOOLS), h(LIVE, timeout=5)],
        "subagentStop": [h(LIVE, timeout=5)],
        "stop": [h(FLOW_STOP, timeout=5)],
    }}, indent=2) + "\n"


def wanted():
    out = {}
    for d, ext, fn in ((".claude/rules", ".mdc", rule), (".claude/agents", ".md", agent)):
        kind = d.split("/")[1]
        folder = os.path.join(ROOT, d)
        for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            if name.endswith(".md"):
                out[".cursor/%s/%s%s" % (kind, name[:-3], ext)] = fn(d + "/" + name)
    out[".cursor/hooks.json"] = hooks()
    return out


def generated_on_disk():
    found = []
    for kind in ("rules", "agents"):
        d = os.path.join(ROOT, ".cursor", kind)
        if os.path.isdir(d):
            for name in os.listdir(d):
                p = ".cursor/%s/%s" % (kind, name)
                if os.path.isfile(os.path.join(ROOT, p)) and "cursor_sync.py" in read(p):
                    found.append(p)
    return found


def bad_headers():
    """Agent header lines whose unquoted value YAML would reject (": " or " #" inside it)."""
    out = []
    folder = os.path.join(ROOT, ".claude", "agents")
    for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
        if not name.endswith(".md"):
            continue
        front, _ = split_front(read(".claude/agents/" + name))
        for line in front.split("\n"):
            m = re.match(r"^([\w-]+):[ \t]*(.*)$", line)
            v = m.group(2).strip() if m else ""
            if v and v[0] not in "\"'[{>|" and (": " in v or " #" in v):
                out.append(".claude/agents/%s: %s: has \": \" or \" #\" in an unquoted value; reword or quote it"
                           % (name, m.group(1)))
    return out


def main():
    check = "--check" in sys.argv
    if "--fix-settings" in sys.argv:
        print("%s: %d hook command(s) now use the Claude launcher" % (SETTINGS, len(settings_hooks(fix=True))))
        sys.exit(0)
    bad = bad_headers()
    for b in bad:
        print("header " + b)
    direct = settings_hooks()
    for c in direct:
        print("hook   %s: %s fails in Cursor (it runs these hooks too, without CLAUDE_PROJECT_DIR)" % (SETTINGS, c[:90]))
    if direct:
        print("fix it: python .claude/core/scripts/cursor_sync.py --fix-settings")
    bad = bad + direct
    want = wanted()
    stale = [p for p, text in want.items() if not os.path.isfile(os.path.join(ROOT, p)) or read(p) != text]
    orphans = [p for p in generated_on_disk() if p not in want]
    if check:
        for p in stale + orphans:
            print(("orphan " if p in orphans else "stale  ") + p)
        print("fix the lines above, then run: python .claude/core/scripts/cursor_sync.py" if bad else
              "ok" if not (stale or orphans) else "run: python .claude/core/scripts/cursor_sync.py")
        sys.exit(1 if stale or orphans or bad else 0)
    for p in stale:
        full = os.path.join(ROOT, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline=NEWLINE) as f:
            f.write(want[p])
        print("wrote  " + p)
    for p in orphans:
        os.remove(os.path.join(ROOT, p))
        print("removed " + p)
    print("%d up to date, %d written, %d removed" % (len(want) - len(stale), len(stale), len(orphans)))


if __name__ == "__main__":
    main()
